const assert = require('node:assert/strict')
const fs = require('node:fs')
const crypto = require('node:crypto')
const origin = 'http://127.0.0.1:3109'
const state = JSON.parse(fs.readFileSync('/tmp/hawco-improvements-qa/browser-state.json', 'utf8'))
const headers = { Cookie: state.cookies.map(c => `${c.name}=${c.value}`).join('; '), 'Content-Type': 'application/json' }
async function request(path, method = 'GET', body, expected = 200) {
  const res = await fetch(origin + path, { method, headers, body: body === undefined ? undefined : JSON.stringify(body) })
  const data = await res.json()
  assert.equal(res.status, expected, `${method} ${path}: ${JSON.stringify(data)}`)
  return data
}
async function main() {
  const seed = { type: 'PILOT_SCRIPT', title: 'QA North Shore — First Draft', fileUrl: 'https://mail.google.com/mail/u/0/#inbox/qa-test-reference', createProject: true, newWriter: { name: 'QA Writer' }, markAsRead: true, intakeKey: crypto.randomUUID() }
  const first = await request('/api/materials', 'POST', seed, 200)
  assert(first.readAt, 'Read selection must persist on material')
  const retry = await request('/api/materials', 'POST', seed, 200)
  assert.equal(retry.id, first.id)
  await request('/api/materials', 'POST', { ...seed, title: 'Conflicting retry' }, 409)
  await request(`/api/projects/${first.projectId}`, 'PATCH', { status: 'EARLY_DEVELOPMENT' })
  const second = await request('/api/materials', 'POST', { type: 'PILOT_SCRIPT', title: 'QA North Shore — Revised Draft', fileUrl: seed.fileUrl, projectId: first.projectId, intakeKey: crypto.randomUUID() }, 200)
  assert.equal(second.readAt, null)
  await request(`/api/projects/${first.projectId}`, 'PATCH', { status: 'PASSED' })
  let unread = await request(`/api/materials?projectId=${first.projectId}&read=unread`)
  assert(unread.some(m => m.id === second.id), 'Pass must not fabricate reading')
  await request(`/api/materials/${second.id}`, 'PATCH', { markAsRead: true })
  let project = await request(`/api/projects/${first.projectId}`)
  assert.equal(project.status, 'PASSED', 'Reading must not undo the project decision')
  await request(`/api/materials/${second.id}`, 'PATCH', { markAsRead: false })
  await request(`/api/projects/${first.projectId}`, 'PATCH', { status: 'CONSIDERING' })
  await request(`/api/projects/${first.projectId}/versions`, 'PATCH', { materialId: first.id, familyId: 'Pilot', approved: true })
  await request(`/api/projects/${first.projectId}/versions`, 'PATCH', { materialId: second.id, familyId: 'Pilot', supersedesId: first.id, approved: false })
  const before = await request(`/api/materials?projectId=${first.projectId}`)
  assert(before.find(m => m.id === first.id).approvedAt)
  await request(`/api/projects/${first.projectId}/versions`, 'PATCH', { materialId: second.id, familyId: 'Pilot', supersedesId: first.id, approved: true })
  const after = await request(`/api/materials?projectId=${first.projectId}`)
  assert.equal(after.filter(m => m.approvedAt).length, 1)
  assert(after.find(m => m.id === second.id).approvedAt)
  await request(`/api/projects/${first.projectId}/release`, 'PATCH', { status: 'VALID', evidence: '' }, 400)
  await request(`/api/projects/${first.projectId}/release`, 'PATCH', { status: 'NEEDS_REVIEW', evidence: 'Synthetic QA release awaiting review' })
  const action = await request('/api/follow-ups', 'POST', { projectId: first.projectId, contactId: first.writerId, note: 'QA Request revised outline', ownerName: 'Philip', dueAt: '2026-10-06', waitingOn: 'Writer' }, 201)
  assert((await request(`/api/follow-ups?projectId=${first.projectId}`)).some(x => x.id === action.id))
  assert((await request(`/api/follow-ups?contactId=${first.writerId}`)).some(x => x.id === action.id))
  assert((await request('/api/follow-ups', 'PATCH', { id: action.id, completed: true })).completedAt)
  assert.equal((await request('/api/follow-ups', 'PATCH', { id: action.id, completed: false })).completedAt, null)
  const upload = new FormData(); upload.append('file', new Blob(['Synthetic local QA document. No confidential content.'], { type: 'text/plain' }), 'qa-document.txt')
  const response = await fetch(origin + '/api/upload', { method: 'POST', headers: { Cookie: headers.Cookie }, body: upload })
  assert.equal(response.status, 200)
  const stored = await response.json()
  assert(stored.url.startsWith('/api/files/'))
  const uploaded = await request('/api/materials', 'POST', { type: 'ONE_PAGER', title: 'QA Uploaded Outline', fileUrl: stored.url, filename: stored.filename, projectId: first.projectId, intakeKey: crypto.randomUUID() }, 200)
  const download = await fetch(origin + `/api/materials/${uploaded.id}/download`, { headers: { Cookie: headers.Cookie } })
  assert.equal(await download.text(), 'Synthetic local QA document. No confidential content.')
  const unauth = await fetch(origin + stored.url, { redirect: 'manual' }); assert.equal(unauth.status, 307)
  const search = await request('/api/search?q=QA')
  fs.writeFileSync('/tmp/hawco-improvements-qa/fixtures.json', JSON.stringify({ projectId: first.projectId, materialId: second.id, contactId: first.writerId, actionId: action.id, searchKeys: Object.keys(search) }))
  const page = await fetch(origin, { headers: { Cookie: headers.Cookie } }); const html = await page.text()
  assert(html.includes('QA North Shore'), 'Today renders unread draft on considered project')
  assert(html.includes('QA Request revised outline'), 'Today renders linked follow-up')
  console.log('PASS: actual HTTP + PostgreSQL intake retry/conflict, independent reads, versions, release validation, linked follow-ups/undo, private local upload/download/auth, search and Today rendering. Synthetic fixtures retained for browser QA.')
}
main().catch(error => { console.error(error.message); process.exit(1) })
