const assert = require('node:assert/strict')
const fs = require('node:fs')
const ts = require('typescript')
const output = ts.transpileModule(fs.readFileSync('src/lib/funding-deadlines.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText
const loaded = { exports: {} }; new Function('exports', 'module', output)(loaded.exports, loaded)
const { fundingDeadlineInput, fundingDaysLeft, fundingCountdown, isDateOnly } = loaded.exports
assert.equal(isDateOnly('2028-02-29'), true)
assert.equal(isDateOnly('2027-02-29'), false)
assert.equal(isDateOnly('2026-04-31'), false)
assert.equal(isDateOnly('2026-10-07T00:00:00Z'), false)
assert.equal(fundingDaysLeft('2026-10-06', '2026-10-07T01:42:00Z'), 0)
assert.equal(fundingDaysLeft('2026-10-06', '2026-10-07T04:01:00Z'), -1)
assert.equal(fundingDaysLeft('2026-03-09', '2026-03-07T17:00:00Z'), 2)
assert.equal(fundingDaysLeft('2026-11-02', '2026-10-31T16:00:00Z'), 2)
assert.equal(fundingDaysLeft('2028-03-01', '2028-02-28T17:00:00Z'), 2)
assert.equal(fundingCountdown('2026-10-06', '2026-10-06T16:00:00Z'), 'Closes today')
assert.equal(fundingCountdown('2026-10-07', '2026-10-06T16:00:00Z'), '1 day left')
assert.equal(fundingCountdown('2026-10-05', '2026-10-06T16:00:00Z'), '1 day ago')
assert.throws(() => fundingDeadlineInput({ program: 'Program', closingDate: '2026-02-30' }, true), /valid closing date/)
assert.throws(() => fundingDeadlineInput({ program: ' ', closingDate: '2026-10-07' }, true), /Program name/)
assert.throws(() => fundingDeadlineInput({ sourceUrl: 'javascript:alert(1)' }), /HTTP or HTTPS/)
assert.throws(() => fundingDeadlineInput({ sourceUrl: 'https://username:password@example.invalid' }), /without credentials/)
assert.throws(() => fundingDeadlineInput({ status: 'VERIFIED' }), /tentative or confirmed/)
assert.throws(() => fundingDeadlineInput({ archived: 'true' }), /true or false/)
assert.throws(() => fundingDeadlineInput({ closingDate: 'tomorrow' }), /valid closing date/)
assert.equal(fundingDeadlineInput({ program: ' Pilot Fund ', closingDate: '2026-10-07' }, true).program, 'Pilot Fund')
assert.equal(fundingDeadlineInput({ program: 'Pilot Fund', closingDate: '2026-10-07' }, true).status, undefined)
assert.equal(fundingDeadlineInput({ archived: true }).archived, true)
assert.equal(fundingDeadlineInput({ sourceUrl: '' }).sourceUrl, null)
console.log('✓ Funding validation + date-only leap/DST/Toronto evening countdowns (23 assertions)')
