const assert = require('node:assert/strict')
const ts = require('typescript')
const fs = require('node:fs')
function load(file) { const output = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText; const module = { exports: {} }; new Function('exports', 'module', output)(module.exports, module); return module.exports }
const { followUpInput, followUpUrgency } = load('src/lib/follow-up-input.ts')
const { validateVersionLink } = load('src/lib/material-version-input.ts')
assert.throws(() => followUpInput({ note: 'task' }, true), /contact or project/)
assert.throws(() => followUpInput({ projectId: 'p', note: ' ' }, true), /description/)
assert.throws(() => followUpInput({ dueAt: 'garbage' }), /Invalid due date/)
assert.throws(() => followUpInput({ completed: 'yes' }), /true or false/)
assert.equal(followUpInput({ contactId: 'c', note: ' Call back ' }, true).note, 'Call back')
assert.equal(followUpInput({ completed: false }).completedAt, null)
assert.ok(followUpInput({ completed: true }).completedAt instanceof Date)
assert.equal(followUpUrgency({ completed: false, dueAt: '2026-10-06', waitingOn: 'Reader' }, new Date('2026-10-07T16:00:00Z')), 'Overdue')
assert.equal(followUpUrgency({ completed: false, dueAt: '2026-10-07' }, new Date('2026-10-07T16:00:00Z')), 'Due today')
assert.equal(followUpUrgency({ completed: true, dueAt: '2026-10-01' }), 'Completed')
const versions = [{ id: 'v1', familyId: 'Pilot', supersedesId: null }, { id: 'v2', familyId: 'Pilot', supersedesId: 'v1' }, { id: 'v3', familyId: null, supersedesId: null }]
assert.equal(validateVersionLink(versions, 'v3', 'Pilot', 'v2').familyId, 'Pilot')
assert.throws(() => validateVersionLink(versions, 'outside-project', 'Pilot', null), /not linked/)
assert.throws(() => validateVersionLink(versions, 'v3', 'Pilot', 'outside-project'), /same project/)
assert.throws(() => validateVersionLink(versions, 'v3', 'Bible', 'v2'), /same project and family/)
assert.throws(() => validateVersionLink(versions, 'v2', 'Pilot', 'v2'), /different version/)
assert.throws(() => validateVersionLink(versions, 'v1', 'Pilot', 'v2'), /cycle/)
assert.throws(() => validateVersionLink(versions, 'v1', 'Bible', null), /same family/)
console.log('✓ Follow-up validation, completion/undo, urgency, version family/cycle/cross-project guards (17 assertions)')

assert.equal(followUpUrgency({ completed: false, dueAt: '2026-10-06' }, new Date('2026-10-07T01:42:00Z')), 'Due today')
assert.equal(followUpUrgency({ completed: false, dueAt: '2026-10-06' }, new Date('2026-10-07T04:01:00Z')), 'Overdue')
assert.equal(followUpUrgency({ completed: false, dueAt: '2026-01-06' }, new Date('2026-01-07T04:42:00Z')), 'Due today')
console.log('✓ Toronto evening boundary in daylight and standard time')
